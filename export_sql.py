"""
Write sql/insert_data.sql: INSERT statements that load the combined workbook
(output/International_airline_activity_yearly_ALL.xlsx) into the MySQL tables
created by sql/create_tables.sql.

Usage:
    python export_sql.py
    mysql -u <user> -p < sql/create_tables.sql
    mysql -u <user> -p < sql/insert_data.sql

The data file empties each table first (DELETE, inside one transaction), so it can be re-run.
Column types and decimal places are read from create_tables.sql, so values are
rounded to fit each column.
"""
import math
import os
import re
import warnings

import pandas as pd

warnings.filterwarnings("ignore")
HERE = os.path.dirname(os.path.abspath(__file__))
WORKBOOK = os.path.join(HERE, "output", "International_airline_activity_yearly_ALL.xlsx")
SCHEMA = os.path.join(HERE, "sql", "create_tables.sql")
OUT = os.path.join(HERE, "sql", "insert_data.sql")
BATCH = 500

SHEETS = {  # sheet -> table
    "Summary": "summary_by_year",
    "Monthly_series": "monthly_series",
    "T1_Traffic_by_operator": "t1_traffic_by_operator",
    "T2_Market_share": "t2_market_share",
    "T3_Capacity_utilisation": "t3_capacity_utilisation",
    "T4_Airports": "t4_airports",
    "T5_City_pairs": "t5_city_pairs",
}
RENAME = {  # sheet column -> SQL column, where they differ beyond case (IN / OUT are reserved in MySQL)
    "T4_Airports": {"In_prev": "inbound_prev", "In": "inbound", "In_change_pct": "inbound_change_pct",
                    "Out_prev": "outbound_prev", "Out": "outbound", "Out_change_pct": "outbound_change_pct"},
}


def schema_columns():
    """{table: {column: (type, scale)}} for the non-generated, non-auto-increment columns."""
    sql = open(SCHEMA, encoding="utf-8").read()
    tables = {}
    for name, body in re.findall(r"CREATE TABLE (\w+) \((.*?)\n\) ENGINE", sql, re.S):
        cols = {}
        for line in body.splitlines():
            m = re.match(r"\s+(\w+)\s+(DECIMAL\((\d+),(\d+)\)|\w+)", line)
            if not m or m.group(1).upper() in ("PRIMARY", "UNIQUE", "KEY"):
                continue
            if "GENERATED" in line or "AUTO_INCREMENT" in line:
                continue
            col, typ = m.group(1), m.group(2).upper()
            cols[col] = (typ, int(m.group(4)) if m.group(4) else None)
        tables[name] = cols
    return tables


def sql_value(v, typ, scale):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "NULL"
    if typ.startswith(("INT", "SMALLINT", "TINYINT")):
        return str(int(round(float(v))))
    if typ.startswith("DECIMAL"):
        return f"{round(float(v), scale):.{scale}f}"
    s = str(v).replace("\\", "\\\\").replace("'", "''")
    return f"'{s}'"


def main():
    tables = schema_columns()
    lines = [
        "-- Data for the tables in sql/create_tables.sql (run that file first).",
        "-- Generated by export_sql.py from output/International_airline_activity_yearly_ALL.xlsx.",
        "-- Source: BITRE International Airline Activity monthly publications. © Commonwealth of Australia.",
        "-- Re-runnable: each table is emptied before loading.",
        "",
        "SET NAMES utf8mb4;",
        "USE airline_activity;",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "START TRANSACTION;",
        "",
    ]
    counts = {}
    for sheet, table in SHEETS.items():
        df = pd.read_excel(WORKBOOK, sheet)
        ren = RENAME.get(sheet, {})
        cols = [ren.get(c, c.lower()) for c in df.columns]
        spec = tables[table]
        missing = [c for c in cols if c not in spec]
        extra = [c for c in spec if c not in cols]
        if missing or extra:
            raise SystemExit(f"{sheet} -> {table}: sheet columns not in schema {missing}; schema columns not in sheet {extra}")
        rows = [
            "(" + ", ".join(sql_value(v, *spec[c]) for c, v in zip(cols, rec)) + ")"
            for rec in df.astype(object).where(df.notna(), None).itertuples(index=False, name=None)
        ]
        counts[table] = len(rows)
        lines.append(f"-- {table}: {len(rows)} rows (sheet {sheet})")
        lines.append(f"DELETE FROM {table};")
        collist = ", ".join(cols)
        for i in range(0, len(rows), BATCH):
            lines.append(f"INSERT INTO {table} ({collist}) VALUES\n  " + ",\n  ".join(rows[i:i + BATCH]) + ";")
        lines.append("")
    lines += ["COMMIT;", "SET FOREIGN_KEY_CHECKS = 1;", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, HERE)}: " + ", ".join(f"{t} {n}" for t, n in counts.items()))
    return counts


if __name__ == "__main__":
    main()
